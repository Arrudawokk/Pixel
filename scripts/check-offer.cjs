/* Run with Playwright available. Evidence is written outside the published site. */
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = path.resolve(__dirname, '..');
const artifacts = path.resolve(process.env.QA_ARTIFACT_DIR || path.join(root, '..', 'pixel-qa'));
const key = 'pintasurpresa:complete-offer:v1';
const mime = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css', '.svg': 'image/svg+xml', '.png': 'image/png', '.json': 'application/json', '.pdf': 'application/pdf' };
const configured = `window.STORE_CONFIG={plans:{complete:{price:'27,99',regularPrice:'37,99',checkoutUrl:'https://example.invalid/promocao'}}};`;
const server = http.createServer((req, res) => {
  const pathname = decodeURIComponent(new URL(req.url, 'http://localhost').pathname);
  const file = path.resolve(root, '.' + (pathname === '/' ? '/index.html' : pathname));
  if (!file.startsWith(root + path.sep) || !fs.existsSync(file) || !fs.statSync(file).isFile()) { res.writeHead(404); res.end(); return; }
  res.setHeader('Content-Type', mime[path.extname(file)] || 'application/octet-stream');
  res.end(fs.readFileSync(file));
});
const checks = [];
const renderedEvidence = [];
let browser;
(async () => {
  fs.mkdirSync(artifacts, { recursive: true });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const url = `http://127.0.0.1:${server.address().port}/`;
  browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) });
  for (const [width, height] of [[1440, 900], [390, 844], [360, 640]]) {
    const context = await browser.newContext({ viewport: { width, height }, reducedMotion: 'reduce' });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('response', r => { if (r.status() >= 400) errors.push(`${r.status()} ${r.url()}`); });
    await page.goto(url);
    await page.waitForFunction(() => document.querySelectorAll('#pixel-grid button').length === 144);
    await page.evaluate(() => document.querySelectorAll('img').forEach(i => i.loading = 'eager'));
    await page.waitForFunction(() => [...document.images].every(i => i.complete && i.naturalWidth > 0));
    assert.equal(await page.locator('[data-checkout]').count(), 1);
    assert.equal(await page.locator('[data-checkout="normal"]').count(), 0);
    assert.doesNotMatch(await page.locator('body').innerText(), /plano normal|14,90|comparar planos|escolha seu plano/i);
    assert.equal(await page.locator('.offer-bonus').count(), 4);
    assert.equal(await page.locator('[data-price="complete"]').innerText(), '27,99');
    assert.equal(await page.locator('[data-regular-price]').innerText(), '37,99');
    assert.equal(await page.locator('#checkout').getAttribute('href'), 'https://pay.cakto.com.br/6xtrnih_1227455');
    assert.equal(await page.locator('#checkout').getAttribute('aria-disabled'), null);
    assert.match(await page.locator('#payment-note').innerText(), /0,99.*taxa/);
    const cta = await page.locator('#checkout').boundingBox();
    assert(cta.height >= 44 && cta.y + cta.height <= height, `CTA must fit first viewport: ${width}x${height}, ${JSON.stringify(cta)}`);
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Horizontal overflow');
    assert.equal(await page.locator('html').evaluate(e => getComputedStyle(e).scrollBehavior), 'auto');
    for (let i = 0; i < 4; i++) await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'checkout');
    assert.notEqual(await page.locator('#checkout').evaluate(e => getComputedStyle(e).outlineStyle), 'none');
    assert.equal(page.url(), url);
    await page.locator('#checkout').blur();
    await page.evaluate(() => window.scrollTo(0, 0));
    const viewport = `${width}x${height}`;
    await page.screenshot({ path: path.join(artifacts, `${viewport}.png`) });
    renderedEvidence.push({ viewport, artifact: `${viewport}.png`, observation: 'Oferta única com preço e CTA na primeira tela, imagens carregadas, sem overflow; bônus na lateral no desktop e abaixo da compra no mobile.' });
    if (width === 390) await page.locator('.offer-bonuses').screenshot({ path: path.join(artifacts, 'bonus-mobile.png') });
    for (const [value, cells] of [['0', 144], ['1', 400], ['2', 576]]) {
      await page.selectOption('#drawing', value);
      assert.equal(await page.locator('#pixel-grid button').count(), cells);
      await page.click('#reveal');
      assert.match(await page.locator('#demo-status').innerText(), /revelou/);
    }
    const pdf = await page.request.get(url + 'assets/amostra-panda.pdf');
    assert.equal(pdf.status(), 200);
    assert.equal((await pdf.body()).subarray(0, 4).toString(), '%PDF');
    assert.deepEqual(errors, []);
    checks.push(`${viewport}: first-screen CTA, 12 loaded images, 4 bonus kits, keyboard focus, reduced motion, 3 demo grids, PDF, no errors`);
    await context.close();
  }
  const context = await browser.newContext();
  await context.route('**/config.js', r => r.fulfill({ contentType: 'text/javascript', body: configured }));
  const page = await context.newPage();
  await page.goto(url);
  assert.equal(await page.locator('#checkout').getAttribute('href'), 'https://example.invalid/promocao');
  await page.evaluate(k => sessionStorage.setItem(k, String(Date.now() - 3600000)), key);
  await page.reload();
  assert.equal(await page.locator('[data-price="complete"]').innerText(), '27,99');
  assert.equal(await page.locator('#checkout').getAttribute('href'), 'https://example.invalid/promocao');
  assert.equal(await page.locator('#offer-countdown, #offer-clock, #offer-ended, [role="timer"]').count(), 0);
  assert.equal(await page.locator('#original-price').isVisible(), true);
  await page.clock.install();
  await page.clock.fastForward(50 * 60 * 1000);
  assert.equal(await page.locator('[data-price="complete"]').innerText(), '27,99');
  assert.equal(await page.locator('#checkout').getAttribute('href'), 'https://example.invalid/promocao');
  assert.equal(await page.locator('#checkout').getAttribute('aria-disabled'), null);
  checks.push('No timer: legacy expired session and reload keep promotional checkout active; advancing 50 minutes does not change amount or disable CTA.');
  await context.close();
  const missing = await browser.newContext();
  await missing.route('**/config.js', r => r.fulfill({ contentType: 'text/javascript', body: 'window.STORE_CONFIG={plans:{complete:{}}};' }));
  const missingPage = await missing.newPage();
  await missingPage.goto(url);
  assert.equal(await missingPage.locator('#checkout').getAttribute('aria-disabled'), 'true');
  assert.equal(await missingPage.locator('#checkout').getAttribute('href'), null);
  await missingPage.locator('#checkout').focus();
  await missingPage.keyboard.press('Enter');
  assert.equal(missingPage.url(), url);
  assert.match(await missingPage.locator('#sales-state').innerText(), /Compras em breve/);
  checks.push('Missing checkout: focusable disabled link, no href, Enter does not navigate, visible unavailable state.');
  await missing.close();
  const blocked = await browser.newContext();
  await blocked.addInitScript(() => { Storage.prototype.getItem = () => { throw new Error('storage unavailable'); }; });
  const blockedPage = await blocked.newPage();
  await blockedPage.goto(url);
  assert.equal(await blockedPage.locator('[data-price="complete"]').innerText(), '27,99');
  assert.equal(await blockedPage.locator('#offer-countdown').isVisible(), false);
  assert.equal(await blockedPage.locator('#checkout').getAttribute('href'), 'https://pay.cakto.com.br/6xtrnih_1227455');
  assert.equal(await blockedPage.locator('#checkout').getAttribute('aria-disabled'), null);
  await blockedPage.screenshot({ path: path.join(artifacts, 'storage-indisponivel.png') });
  checks.push('Blocked storage: promotional amount and checkout stay available, without a countdown.');
  await blocked.close();
  const noJs = await browser.newContext({ javaScriptEnabled: false });
  const noJsPage = await noJs.newPage();
  await noJsPage.goto(url);
  assert.equal(await noJsPage.locator('#checkout').getAttribute('href'), 'https://pay.cakto.com.br/6xtrnih_1227455');
  assert.equal(await noJsPage.locator('#checkout').getAttribute('aria-disabled'), null);
  assert.equal(await noJsPage.locator('[data-price="complete"]').innerText(), '27,99');
  checks.push('JavaScript disabled: static checkout link and promotional price remain available.');
  await noJs.close();
  const failed = await browser.newContext();
  await failed.route('**/assets/demonstracao.json', r => r.abort());
  const failedPage = await failed.newPage();
  await failedPage.goto(url);
  await failedPage.waitForFunction(() => document.querySelector('#demo-status').textContent.includes('Não foi possível'));
  assert.equal(await failedPage.locator('#pixel-grid').getAttribute('aria-busy'), 'false');
  checks.push('Failed demo fetch: actionable error message and busy state cleared; sample link remains.');
  await failed.close();
  const loading = await browser.newContext();
  let release;
  const gate = new Promise(r => { release = r; });
  await loading.route('**/assets/demonstracao.json', async r => { await gate; await r.fulfill({ contentType: 'application/json', body: fs.readFileSync(path.join(root, 'assets/demonstracao.json'), 'utf8') }); });
  const loadingPage = await loading.newPage();
  await loadingPage.goto(url, { waitUntil: 'domcontentloaded' });
  assert.equal(await loadingPage.locator('#pixel-grid').getAttribute('aria-busy'), 'true');
  assert.match(await loadingPage.locator('#demo-status').innerText(), /Preparando/);
  release();
  await loadingPage.waitForFunction(() => document.querySelectorAll('#pixel-grid button').length === 144);
  checks.push('Loading demo: reserved square grid and loading status before data; successful render after response.');
  await loading.close();
  fs.writeFileSync(path.join(artifacts, 'checks.json'), JSON.stringify({ checks, renderedEvidence }, null, 2));
  console.log(JSON.stringify({ passed: true, checks, artifacts }, null, 2));
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => { if (browser) await browser.close(); server.closeAllConnections(); server.close(); });
